-- WEBITAS · esquema para Supabase
-- Cómo usarlo:
--   1. Supabase → SQL Editor → New query.
--   2. Pega TODO este archivo → Run.
--   3. Importa tus prospectos:
--        · Table Editor → prospectos → Insert → Import data from CSV, o
--        · node tools/supabase-import.mjs "WEBITAS - prospectos_consolidado.csv" --replace
--
-- Columnas = el esquema único de WEBITAS (28 → 25; se quitaron contacto, tiktok y publicar,
-- que no usaba el sistema). Los nombres coinciden con el CSV para importar sin mapear.

create table if not exists public.prospectos (
  id                bigint generated by default as identity primary key,
  negocio           text not null,
  rubro             text not null,
  categoria         text,
  direccion         text,
  zona              text,
  ciudad            text,
  maps_url          text,
  telefono          text,
  email             text,
  horarios          text,
  instagram         text,
  instagram_url     text,
  facebook          text,
  web_actual        text,
  rating            numeric,
  resenas           integer,
  tiene_web         text,
  estado            text default 'Nuevo',
  vendedor          text,
  prioridad_manual  integer,
  proximo_contacto  text,
  ultimo_contacto   text,
  canal             text,
  generar           text,
  notas             text,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);

-- Índice para búsquedas por teléfono (el generador deduplica por teléfono).
create index if not exists prospectos_telefono_idx on public.prospectos (telefono);

-- ---------------------------------------------------------------- seguridad ---
-- El panel público lee con la clave anónima (igual que hoy: el panel ya muestra los datos).
-- Escribir (panel local / import) usa la service_role key, que salta RLS.
alter table public.prospectos enable row level security;

drop policy if exists "lectura anon" on public.prospectos;
create policy "lectura anon" on public.prospectos
  for select using (true);

-- El Gestor edita e inserta SIN login (decisión del dueño; la URL es privada).
-- NO se crea política de borrado: nadie puede vaciar la tabla desde el panel.
drop policy if exists "editar anon" on public.prospectos;
create policy "editar anon" on public.prospectos
  for update using (true) with check (true);

drop policy if exists "insertar anon" on public.prospectos;
create policy "insertar anon" on public.prospectos
  for insert with check (true);

-- ---------------------------------------------------------------- opcional ---
-- Métricas agregadas (el panel ya las calcula en vivo; esto sirve para consultarlas por SQL).
create or replace view public.metricas as
  select estado, vendedor, count(*)::int as n
  from public.prospectos
  group by estado, vendedor;
